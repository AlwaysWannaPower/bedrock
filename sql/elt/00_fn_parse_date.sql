-- ============================================================================
-- Файл: 00_fn_parse_date.sql
--
-- Назначение:
--     Универсальная функция разбора дат из сырого CSV-слоя STAGING.
--
-- Зачем нужна:
--     Заказчик присылает даты в ДВУХ разных видах:
--
--       1. Числовой формат (Excel Serial Date) — для экономии размера файла:
--             45292  ->  2024-01-01
--             45323.0 -> 2024-02-01   (может быть с дробной частью ".0")
--
--       2. Обычный текстовый формат даты:
--             2024-01-31  (yyyy-mm-dd)
--             31.01.2024  (dd.mm.yyyy)
--             31/01/2024  (dd/mm/yyyy)
--             и т.п.
--
--     Функция сама определяет вид даты и преобразует её в тип DATE.
--
--     Если разобрать дату не удалось — возвращает NULL.
--     NULL затем попадает в QUARANTINE с причиной «Некорректная дата».
--
-- Как работает:
--
--     1. Убираем лишние пробелы.
--     2. Если значение состоит ТОЛЬКО из цифр, точек и запятых —
--        пробуем прочитать его как Excel Serial Date.
--     3. Иначе пробуем самые распространённые текстовые форматы
--        через TRY_CONVERT с разными style-кодами.
--
-- ВАЖНО:
--     TRY_CONVERT (в отличие от CONVERT) НЕ выбрасывает ошибку
--     при неудачном преобразовании — возвращает NULL.
--     Поэтому функция безопасна для любых «грязных» значений.
-- ============================================================================

USE BI_DWH;
GO

-- ============================================================================
-- ВАЖНО: явно включаем SET-параметры.
--     Без QUOTED_IDENTIFIER ON INSERT в таблицы с фильтрованными
--     индексами (например dwh.dim_warehouse) падает с ошибкой 1934,
--     потому что sqlcmd по умолчанию выставляет QUOTED_IDENTIFIER OFF.
-- ============================================================================
SET ANSI_NULLS ON;
GO

SET QUOTED_IDENTIFIER ON;
GO

CREATE OR ALTER FUNCTION elt.fn_parse_date
(
    -- Сырое значение даты из STAGING (все поля там NVARCHAR).
    @value NVARCHAR(100)
)
RETURNS DATE
AS
BEGIN

    -- Локальная переменная для результата.
    DECLARE @result DATE = NULL;

    -- Очищенное значение без пробелов по краям.
    DECLARE @clean NVARCHAR(100) = LTRIM(RTRIM(@value));

    -- ========================================================================
    -- 1. Пустое значение -> NULL
    -- ========================================================================
    -- Пустая строка и NULL — это «нет даты», а не ошибка формата.
    IF @clean IS NULL OR @clean = N''
        RETURN NULL;

    -- ========================================================================
    -- 2. Числовой формат (Excel Serial Date)
    -- ========================================================================
    --
    -- Проверяем, что значение состоит только из цифр, точки или запятой:
    --
    --     '45292'     -> подходит
    --     '45323.0'   -> подходит
    --     '2024-01-31'-> НЕ подходит (есть дефис) -> уйдёт в шаг 3
    --
    -- LIKE N'%[^0-9.,]%'  = «есть хоть один символ, кроме цифр/точки/запятой».
    -- NOT LIKE  -> «НЕТ таких символов».
    --
    IF @clean NOT LIKE N'%[^0-9.,]%'
    BEGIN

        -- Пробуем прочитать значение как число.
        DECLARE @num DECIMAL(18, 2);
        SET @num = TRY_CONVERT(DECIMAL(18, 2), @clean);

        IF @num IS NOT NULL
        BEGIN
            -- Excel Serial Date = число дней, прошедших с 1899-12-30.
            --
            -- FLOOR отбрасывает дробную часть: '45323.0' -> 45323.
            --
            -- Пример:
            --     45292 дней после 1899-12-30 = 2024-01-01
            SET @result = TRY_CONVERT
            (
                DATE,
                DATEADD(DAY, FLOOR(@num), '1899-12-30')
            );

            -- Если получилось — сразу возвращаем.
            IF @result IS NOT NULL
                RETURN @result;
        END;
    END;

    -- ========================================================================
    -- 3. Текстовые форматы даты
    -- ========================================================================
    --
    -- Перебираем распространённые форматы по style-кодам CONVERT:
    --
    --     104  -> dd.mm.yyyy          (31.01.2024)
    --     103  -> dd/mm/yyyy          (31/01/2024)
    --     102  -> yyyy.mm.dd          (2024.01.31)
    --     120  -> yyyy-mm-dd hh:mi:ss (2024-01-31 10:00:00)
    --     112  -> yyyymmdd            (20240131)
    --     126  -> ISO8601             (2024-01-31T10:00:00)
    --
    -- TRY_CONVERT возвращает NULL, если формат не подошёл,
    -- поэтому каждый следующий вариант пробуем только при неудаче.
    -- ========================================================================

    SET @result = TRY_CONVERT(DATE, @clean, 104);
    IF @result IS NOT NULL
        RETURN @result;

    SET @result = TRY_CONVERT(DATE, @clean, 103);
    IF @result IS NOT NULL
        RETURN @result;

    SET @result = TRY_CONVERT(DATE, @clean, 102);
    IF @result IS NOT NULL
        RETURN @result;

    SET @result = TRY_CONVERT(DATE, @clean, 120);
    IF @result IS NOT NULL
        RETURN @result;

    SET @result = TRY_CONVERT(DATE, @clean, 112);
    IF @result IS NOT NULL
        RETURN @result;

    SET @result = TRY_CONVERT(DATE, @clean, 126);
    IF @result IS NOT NULL
        RETURN @result;

    -- ========================================================================
    -- 4. Ни один формат не подошёл
    -- ========================================================================
    -- Возвращаем NULL — вызывающая процедура отправит строку в QUARANTINE.
    RETURN NULL;

END;
GO

