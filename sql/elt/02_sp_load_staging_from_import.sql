-- ============================================================================
-- Файл: 02_load_staging_from_import.sql
--
-- Назначение:
--     Инкрементальная загрузка CSV-файлов из /import в staging-слой.
--
-- Общая схема:
--
--     /import/warehouses/*.csv
--              │
--              ▼
--     elt.sp_load_folder
--              │
--              ├── поиск файлов
--              ├── расчёт SHA-256
--              ├── проверка elt.file_registry
--              ├── загрузка конкретного типа CSV
--              └── обновление статуса файла
--              │
--              ▼
--     staging.bulk_*
--              │
--              ▼
--     staging.*_raw
--
--
-- Для чего нужен elt.file_registry:
--
--     Реестр позволяет понять:
--
--       1. Видели ли мы этот файл раньше?
--       2. Был ли он успешно загружен?
--       3. Изменилось ли его содержимое?
--       4. Если загрузка упала — какую ошибку получили?
--
--
-- Инкрементальная логика:
--
--     Файл впервые появился
--          ↓
--     INSERT в file_registry со статусом pending
--          ↓
--     загрузка
--          ↓
--     status = loaded
--
--
--     Файл уже существует + SHA-256 не изменился + loaded
--          ↓
--     SKIP
--
--
--     Файл существует, но SHA-256 изменился
--          ↓
--     status = pending
--          ↓
--     повторная загрузка
--
--
-- ВАЖНО:
--
--     xp_dirtree используется для получения списка файлов внутри
--     директории, доступной SQL Server.
--
--     OPENROWSET(BULK...) используется для чтения содержимого файла
--     и расчёта SHA-256.
--
-- ============================================================================
USE BI_DWH;
GO

-- ============================================================================
-- ВАЖНО: явно включаем SET-параметры.
--     Без QUOTED_IDENTIFIER ON INSERT в таблицы с фильтрованными
--     индексами (например dwh.dim_warehouse) падает с ошибкой 1934,
--     потому что sqlcmd по умолчанию выставляет QUOTED_IDENTIFIER OFF.
-- ============================================================================
SET ANSI_NULLS ON;
GO

SET QUOTED_IDENTIFIER ON;
GO
-- ============================================================================
-- ПРОЦЕДУРА №1
-- elt.sp_load_folder
--
-- Универсальный загрузчик одной директории.
--
-- Параметры:
--
--     @source_type
--         Тип данных:
--             turnover
--             prices
--             warehouses
--
--     @folder_path
--         Путь к директории, например:
--             /import/turnover
--
--
-- Эта процедура не знает структуру CSV.
--
-- Она отвечает только за общую elt-логику:
--
--     1. Найти файлы.
--     2. Для каждого файла вычислить SHA-256.
--     3. Проверить реестр.
--     4. Решить, нужно ли загружать файл.
--     5. Вызвать специализированный загрузчик.
--     6. Обновить статус.
--
-- ============================================================================

CREATE OR ALTER PROCEDURE elt.sp_load_folder @source_type NVARCHAR(20),
                                             @folder_path NVARCHAR(500)
AS
BEGIN
    SET NOCOUNT ON;
    -- ========================================================================
    -- Локальные переменные
    -- ========================================================================
    -- Имя текущего CSV-файла.
    DECLARE @file_name NVARCHAR(255);

    -- Полный путь к файлу.
    -- Например:
    --     /import/turnover/turnover_2026_01.csv
    --
    DECLARE @file_path NVARCHAR(500);

    -- SHA-256 содержимого файла.
    -- SHA-256 занимает 32 байта.
    DECLARE @file_hash VARBINARY(32);

    -- Размер файла в байтах.
    DECLARE @file_size BIGINT;

    -- ID записи файла в elt.file_registry.
    DECLARE @file_id INT;

    -- Старый SHA-256 из реестра.
    DECLARE @old_hash VARBINARY(32);

    -- Старый статус файла.
    -- Возможные значения в нашей логике:
    --
    --     pending
    --     loaded
    --     failed
    --
    DECLARE @old_status NVARCHAR(20);

    -- ========================================================================
    -- Получаем список объектов в директории
    -- ========================================================================
    --
    -- xp_dirtree — системная расширенная процедура SQL Server.
    --
    -- Она позволяет получить список файлов и каталогов внутри указанного
    -- пути.
    --
    -- Нам здесь нужны только файлы первого уровня.
    --
    -- Третий параметр = 1 означает:
    --
    --     возвращать только файлы.
    --
    -- Но мы всё равно сохраняем isfile и дополнительно фильтруем его ниже,
    -- чтобы логика была очевидной.
    --
    -- Второй параметр = 1 означает глубину поиска:
    --
    --     только указанная директория,
    --     без рекурсивного обхода вложенных каталогов.
    --
    -- ========================================================================

    CREATE TABLE #files
    (
        name   NVARCHAR(512),
        depth  INT,
        isfile BIT
    );


    -- Заполняем временную таблицу результатом xp_dirtree.
    --
    -- #files существует только внутри текущего выполнения процедуры.
    -- После завершения процедуры SQL Server автоматически удалит её.
    INSERT INTO #files
    (name,
     depth,
     isfile)
        EXEC master.sys.xp_dirtree
             @folder_path,
             1,
             1;

    -- ========================================================================
    -- Создаём курсор по CSV-файлам
    -- ========================================================================
    --
    -- Здесь выбираем только:
    --
    --     isfile = 1
    --
    -- то есть реальные файлы.
    --
    -- И:
    --
    --     name LIKE '%.csv'
    --
    -- то есть только CSV.
    --
    -- LOCAL:
    --     курсор существует только внутри этой процедуры.
    --
    -- FAST_FORWARD:
    --     оптимизированный курсор для последовательного чтения
    --     вперёд без возврата назад.
    -- ========================================================================

    DECLARE file_cursor CURSOR LOCAL FAST_FORWARD
        FOR
        SELECT name
        FROM #files
        WHERE isfile = 1
          AND name LIKE '%.csv';


    -- Открываем курсор.
    OPEN file_cursor;


    -- Получаем первый файл.
    FETCH NEXT FROM file_cursor
        INTO @file_name;


    -- ========================================================================
    -- Основной цикл обработки файлов
    -- ========================================================================

    WHILE @@FETCH_STATUS = 0
        BEGIN

            -- ====================================================================
            -- ВАЖНО:
            --
            -- Перед обработкой нового файла обязательно сбрасываем переменные,
            -- которые относятся к предыдущему файлу.
            --
            -- Иначе значение @file_id / @old_hash / @old_status от предыдущей
            -- итерации может повлиять на текущую.
            -- ====================================================================

            SET @file_id = NULL;
            SET @old_hash = NULL;
            SET @old_status = NULL;


            -- --------------------------------------------------------------------
            -- Формируем полный путь к файлу.
            --
            -- Например:
            --
            -- @folder_path = /import/turnover
            -- @file_name   = turnover_2026_01.csv
            --
            -- Результат:
            --
            -- /import/turnover/turnover_2026_01.csv
            -- --------------------------------------------------------------------

            SET @file_path = @folder_path + N'/' + @file_name;

            -- ====================================================================
            -- Вычисляем SHA-256 файла
            -- ====================================================================
            --
            -- SHA-256 используется как fingerprint содержимого файла.
            --
            -- Если пользователь заменит файл новым содержимым, его SHA-256
            -- изменится.
            --
            -- Поэтому мы можем определить:
            --
            --     файл тот же самый
            --
            -- или:
            --
            --     файл был изменён.
            --
            -- ====================================================================

            SET @file_hash = NULL;
            SET @file_size = NULL;


            -- Динамический SQL необходим потому, что путь к BULK-файлу
            -- должен быть передан непосредственно в OPENROWSET.
            DECLARE @hash_sql NVARCHAR(MAX);


            -- Формируем SQL для чтения файла.
            --
            -- SINGLE_BLOB означает:
            --
            --     прочитать весь файл целиком как VARBINARY(MAX).
            --
            -- Затем:
            --
            --     HASHBYTES('SHA2_256', BulkColumn)
            --
            -- вычисляет SHA-256.
            --
            -- DATALENGTH(BulkColumn)
            --
            -- возвращает размер файла в байтах.
            --
            -- REPLACE(...):
            --
            -- если в пути встретится одинарная кавычка,
            -- она должна быть экранирована второй кавычкой.
            SET @hash_sql = N'
            SELECT
                @hash = HASHBYTES(
                    ''SHA2_256'',
                    BulkColumn
                ),

                @size = DATALENGTH(BulkColumn)

            FROM OPENROWSET(
                BULK ''' +
                            REPLACE(@file_path, '''', '''''') +
                            ''',
                            SINGLE_BLOB
                        ) AS src;
                    ';


            -- Выполняем сформированный SQL.
            --
            -- @hash и @size объявлены как OUTPUT-параметры,
            -- поэтому результат попадёт обратно в наши переменные.
            EXEC sp_executesql
                 @hash_sql,
                 N'
                     @hash VARBINARY(32) OUTPUT,
                     @size BIGINT OUTPUT
                 ',
                 @hash = @file_hash OUTPUT,
                 @size = @file_size OUTPUT;


            -- ====================================================================
            -- Ищем файл в реестре
            -- ====================================================================
            --
            -- file_path является идентификатором конкретного файла.
            --
            -- Если запись найдена:
            --
            --     @file_id
            --     @old_hash
            --     @old_status
            --
            -- получат существующие значения.
            --
            -- Если файл не найден:
            --
            --     @file_id останется NULL.
            -- ====================================================================

            SELECT @file_id = file_id,
                   @old_hash = file_hash,
                   @old_status = status
            FROM elt.file_registry
            WHERE file_path = @file_path;
            -- ====================================================================
            -- СЛУЧАЙ №1
            --
            -- Файл встречается впервые.
            -- ====================================================================
            --
            -- Если @file_id IS NULL, записи в реестре ещё нет.
            --
            -- Добавляем её со статусом pending.
            --
            -- pending означает:
            --
            --     "файл зарегистрирован, но его загрузка ещё не завершена".
            -- ====================================================================

            IF @file_id IS NULL
                BEGIN

                    INSERT INTO elt.file_registry
                    (source_type,
                     file_name,
                     file_path,
                     file_hash,
                     file_size_bytes,
                     status)
                    VALUES (@source_type,
                            @file_name,
                            @file_path,
                            @file_hash,
                            @file_size,
                            N'pending');


                    -- SCOPE_IDENTITY() возвращает ID только что созданной записи.
                    --
                    -- Он нужен нам, чтобы после загрузки обновить именно эту запись.
                    SET @file_id = CONVERT(INT, SCOPE_IDENTITY());


                    PRINT
                        N'NEW FILE: ' + @file_path;

                END;


            -- ====================================================================
            -- СЛУЧАЙ №2
            --
            -- Файл уже был успешно загружен и его содержимое не изменилось.
            -- ====================================================================
            --
            -- Одновременно должны выполняться три условия:
            --
            --     1. Старый hash существует.
            --     2. Старый hash совпадает с текущим.
            --     3. Предыдущая загрузка завершилась loaded.
            --
            -- Тогда файл можно безопасно пропустить.
            --
            -- Никакого BULK INSERT выполнять не нужно.
            -- ====================================================================

            IF @old_hash IS NOT NULL
                AND @old_hash = @file_hash
                AND @old_status = N'loaded'
                BEGIN

                    PRINT
                        N'SKIP: ' + @file_path;

                END


                -- ====================================================================
                -- СЛУЧАЙ №3
                --
                -- Файл нужно загрузить.
                --
                -- Сюда попадём, если:
                --
                --     1. Это новый файл.
                --     2. Файл раньше загружался, но его содержимое изменилось.
                --     3. Предыдущая загрузка завершилась failed.
                --     4. Файл имеет другой статус и его необходимо обработать.
                -- ====================================================================

            ELSE
                BEGIN

                    -- ---------------------------------------------------------------
                    -- Для одного файла создаём отдельный TRY/CATCH.
                    --
                    -- Это позволяет:
                    --
                    --     1. поймать ошибку конкретного CSV;
                    --     2. записать её в file_registry;
                    --     3. после этого повторно выбросить ошибку через THROW.
                    --
                    -- ВАЖНО:
                    --
                    -- Правильная конструкция SQL Server:
                    --
                    --     BEGIN TRY
                    --         ...
                    --     END TRY
                    --     BEGIN CATCH
                    --         ...
                    --     END CATCH
                    --
                    -- Именно здесь в исходном файле была синтаксическая ошибка:
                    --
                    --     END
                    --     TRY
                    --
                    -- вместо:
                    --
                    --     END TRY
                    -- ---------------------------------------------------------------

                    BEGIN TRY

                        PRINT
                            N'LOAD: ' + @file_path;


                        -- ============================================================
                        -- Обновляем информацию о файле перед загрузкой
                        -- ============================================================
                        --
                        -- Это особенно важно для изменившегося файла.
                        --
                        -- Например:
                        --
                        -- вчера:
                        --     hash = ABC
                        --     status = loaded
                        --
                        -- сегодня:
                        --     hash = XYZ
                        --
                        -- Значит файл был изменён.
                        --
                        -- Мы сохраняем новый hash и переводим файл обратно
                        -- в pending.
                        -- ============================================================

                        UPDATE elt.file_registry
                        SET file_hash       = @file_hash,
                            file_size_bytes = @file_size,
                            status          = N'pending',
                            error_message   = NULL
                        WHERE file_id = @file_id;


                        -- ============================================================
                        -- Выбираем специализированный загрузчик
                        -- ============================================================
                        --
                        -- Общая процедура не знает структуру конкретного CSV.
                        --
                        -- Поэтому она делегирует работу соответствующей процедуре.
                        --
                        -- turnover:
                        --     elt.sp_bulk_turnover_direct
                        --
                        -- prices:
                        --     elt.sp_bulk_prices_direct
                        --
                        -- warehouses:
                        --     elt.sp_bulk_warehouses_direct
                        -- ============================================================


                        -- ------------------------------------------------------------
                        -- Оборот
                        -- ------------------------------------------------------------

                        IF @source_type = N'turnover'
                            BEGIN

                                EXEC elt.sp_bulk_turnover_direct
                                     @file_id = @file_id,
                                     @file_path = @file_path;

                            END


                            -- ------------------------------------------------------------
                            -- Цены
                            -- ------------------------------------------------------------

                        ELSE
                            IF @source_type = N'prices'
                                BEGIN

                                    EXEC elt.sp_bulk_prices_direct
                                         @file_id = @file_id,
                                         @file_path = @file_path;

                                END


                                -- ------------------------------------------------------------
                                -- Склады
                                -- ------------------------------------------------------------

                            ELSE
                                IF @source_type = N'warehouses'
                                    BEGIN

                                        EXEC elt.sp_bulk_warehouses_direct
                                             @file_id = @file_id,
                                             @file_path = @file_path;

                                    END


                                    -- ------------------------------------------------------------
                                    -- Неизвестный тип источника
                                    -- ------------------------------------------------------------
                                    --
                                    -- Это защитная проверка.
                                    --
                                    -- Если кто-нибудь случайно вызовет:
                                    --
                                    --     EXEC elt.sp_load_folder
                                    --         @source_type = N'abc',
                                    --         ...
                                    --
                                    -- мы не должны молча продолжать выполнение.
                                    --
                                    -- THROW 50001:
                                    --
                                    --     50001 — пользовательский номер ошибки;
                                    --     текст — описание проблемы;
                                    --     1 — state.
                                    -- ------------------------------------------------------------

                                ELSE
                                    BEGIN

                                        THROW 50001,
                                            'Неизвестный тип источника',
                                            1;

                                    END;


                        -- ============================================================
                        -- Если мы дошли сюда, специализированная процедура
                        -- завершилась успешно.
                        --
                        -- Следовательно, можно отметить файл как loaded.
                        -- ============================================================

                        UPDATE elt.file_registry
                        SET status    = N'loaded',
                            loaded_at = SYSDATETIME()
                        WHERE file_id = @file_id;


                        PRINT
                            N'LOADED: ' + @file_path;


                    END TRY


                    -- =================================================================
                    -- CATCH конкретного файла
                    -- =================================================================

                    BEGIN CATCH

                        -- -------------------------------------------------------------
                        -- Если специализированный загрузчик упал,
                        -- фиксируем failed в реестре.
                        --
                        -- ERROR_MESSAGE() возвращает текст реальной ошибки SQL Server.
                        --
                        -- Например:
                        --
                        --     Conversion failed when converting...
                        --
                        --     Cannot bulk load...
                        --
                        --     Invalid object name...
                        --
                        -- и т.д.
                        -- -------------------------------------------------------------

                        UPDATE elt.file_registry
                        SET status        = N'failed',
                            error_message = ERROR_MESSAGE()
                        WHERE file_id = @file_id;


                        -- -------------------------------------------------------------
                        -- После записи ошибки повторно выбрасываем исходную ошибку.
                        --
                        -- Это принципиально важно.
                        --
                        -- Если просто проглотить ошибку:
                        --
                        --     SQL Server / SQL Agent
                        --
                        -- может решить, что процедура завершилась успешно.
                        --
                        -- THROW сохраняет исходную ошибку и передаёт её выше.
                        -- -------------------------------------------------------------

                        THROW;

                    END CATCH;

                END;


            -- ====================================================================
            -- Переходим к следующему файлу.
            -- ====================================================================

            FETCH NEXT FROM file_cursor
                INTO @file_name;

        END;


    -- ========================================================================
    -- Завершаем работу с курсором
    -- ========================================================================

    -- CLOSE закрывает курсор.
    --
    -- Сам объект курсора после этого ещё существует,
    -- но больше не может использоваться для FETCH.
    CLOSE file_cursor;


    -- DEALLOCATE полностью освобождает объект курсора.
    DEALLOCATE file_cursor;


    -- ========================================================================
    -- Удаляем временную таблицу со списком файлов.
    --
    -- Хотя SQL Server автоматически удалит локальную временную таблицу
    -- при завершении процедуры, явный DROP делает жизненный цикл объекта
    -- очевидным для читающего код.
    -- ========================================================================

    DROP TABLE #files;

END;
GO
-- ============================================================================
-- ПРОЦЕДУРА №2
-- elt.sp_load_staging_from_import
--
-- Главная процедура загрузки.
--
-- Она сама файлы не обрабатывает.
-- Её задача — последовательно вызвать общий загрузчик для трёх директорий:
--
--     /import/warehouses
--     /import/prices
--     /import/turnover
--
-- Благодаря этому SQL Agent в дальнейшем сможет запускать всего одну
-- процедуру:
--
--     EXEC elt.sp_load_staging_from_import;
--
-- ============================================================================

CREATE OR ALTER PROCEDURE elt.sp_load_staging_from_import
AS
BEGIN

    -- SET NOCOUNT ON отключает сообщения вида:
    --
    --     "(10 rows affected)"
    --
    -- Это уменьшает лишний служебный вывод и особенно полезно
    -- для elt-процедур.
    SET NOCOUNT ON;

    -- ========================================================================
    -- TRY
    --
    -- Весь основной процесс помещаем в TRY.
    --
    -- Если любая из вызываемых процедур завершится ошибкой,
    -- выполнение перейдёт в BEGIN CATCH.
    --
    -- Логирование этой процедуры (RUNNING/SUCCESS/ERROR) выполняет
    -- elt.sp_master_etl как шаг 0 — здесь повторно не пишем.
    -- ========================================================================
    BEGIN TRY
        -- --------------------------------------------------------------------
        -- 1. Загрузка складов
        --
        -- Общий загрузчик получает:
        --
        --     source_type = warehouses
        --
        -- Это значение затем используется для выбора конкретной процедуры:
        --
        --     elt.sp_bulk_warehouses_direct
        -- --------------------------------------------------------------------

        EXEC elt.sp_load_folder
             @source_type = N'warehouses',
             @folder_path = N'/import/warehouses';


        -- --------------------------------------------------------------------
        -- 2. Загрузка цен
        --
        -- Здесь используется тот же общий загрузчик,
        -- но передаётся другая директория и тип источника.
        -- --------------------------------------------------------------------

        EXEC elt.sp_load_folder
             @source_type = N'prices',
             @folder_path = N'/import/prices';


        -- --------------------------------------------------------------------
        -- 3. Загрузка оборота
        --
        -- Для каждого найденного CSV будет вызван:
        --
        --     elt.sp_bulk_turnover_direct
        -- --------------------------------------------------------------------

        EXEC elt.sp_load_folder
             @source_type = N'turnover',
             @folder_path = N'/import/turnover';

    END TRY

    -- ========================================================================
    -- CATCH главной процедуры
    --
    -- Сюда попадём, если:
    --
    --     elt.sp_load_folder
    --
    -- или одна из процедур, вызываемых внутри неё, завершится ошибкой.
    -- ========================================================================

    BEGIN CATCH

        -- Пробрасываем исходную ошибку наверх (в elt.sp_master_etl,
        -- который зафиксирует её в etl.elt_log и отправит алерт).
