-- ============================================================================
-- Файл: 01_sp_send_test_mail_in_first_up.sql
--
-- Назначение:
--     Тестовое письмо при ПЕРВОМ разворачивании docker-compose.
--
-- Почему этот файл существует (история проблемы):
--     Раньше процедура только СОЗДАВАЛАСЬ, но никто её не ВЫЗЫВАЛ —
--     поэтому «почтовый модуль не включался»: при старте контейнера
--     письмо не приходило.
--
--     Теперь в конце этого файла процедура сразу ВЫЗЫВАЕТСЯ,
--     и письмо уходит при первом запуске.
--
-- Защита от спама:
--     Письмо отправляется ТОЛЬКО один раз за всю жизнь контейнера.
--     Маркер хранится в таблице elt.mail_test_flag:
--         - если в таблице есть строка — письмо уже отправляли, пропускаем;
--         - если строки нет — отправляем и записываем маркер.
-- ============================================================================

USE BI_DWH;
GO

-- ============================================================================
-- ВАЖНО: явно включаем SET-параметры.
--     Без QUOTED_IDENTIFIER ON INSERT в таблицы с фильтрованными
--     индексами (например dwh.dim_warehouse) падает с ошибкой 1934,
--     потому что sqlcmd по умолчанию выставляет QUOTED_IDENTIFIER OFF.
-- ============================================================================
SET ANSI_NULLS ON;
GO

SET QUOTED_IDENTIFIER ON;
GO

-- Маркер «тестовое письмо уже отправлено».
IF OBJECT_ID('elt.mail_test_flag', 'U') IS NULL
    BEGIN
        CREATE TABLE elt.mail_test_flag
        (
            sent_at DATETIME2 NOT NULL DEFAULT SYSDATETIME()
        );
    END;
GO

CREATE OR ALTER PROCEDURE elt.sp_send_test_mail_in_first_up
AS
BEGIN
    SET NOCOUNT ON;

    -- ========================================================================
    -- 1. Если письмо уже отправляли при прошлых стартах — выходим.
    -- ========================================================================
    IF EXISTS (SELECT 1 FROM elt.mail_test_flag)
    BEGIN
        PRINT N'Тестовое письмо уже отправлялось ранее — пропускаем.';
        RETURN;
    END;

    -- ========================================================================
    -- 2. Если SMTP не настроен — выходим (алерты всё равно идут в базу).
    -- ========================================================================
    IF LEN('$(ADMIN_EMAIL)') = 0
    BEGIN
        PRINT N'ADMIN_EMAIL не задан — тестовое письмо пропущено.';
        RETURN;
    END;

    -- ========================================================================
    -- 3. Отправляем тестовое письмо.
    -- ========================================================================
    BEGIN TRY

        DECLARE @body NVARCHAR(MAX);

        SET @body = N'Добрый день, Администратор!' + CHAR(10) + CHAR(10) +
                    N'Это тест почтового модуля SQL Server при первичном разворачивании docker-compose.';

        EXEC msdb.dbo.sp_send_dbmail
            @profile_name = 'DWH Alerts',
            @recipients   = '$(ADMIN_EMAIL)',
            @subject      = N'BI_DWH: проверка почтового модуля',
            @body         = @body;

        -- Записываем маркер: письмо отправлено.
        INSERT INTO elt.mail_test_flag DEFAULT VALUES;

        PRINT N'✅ Тестовое письмо отправлено на $(ADMIN_EMAIL)';

    END TRY
    BEGIN CATCH

        -- Если почта упала — НЕ роняем startup.
        -- Ошибка печатается в лог контейнера и видна в docker logs.
        PRINT N'❌ Ошибка отправки тестового письма: ' + ERROR_MESSAGE();

    END CATCH;
END;
GO

-- ============================================================================
-- 6. ВЫЗОВ тестовой отправки прямо здесь (при каждом старте контейнера).
--    Внутри процедуры стоит защита: реально письмо уйдёт только один раз.
-- ============================================================================

EXEC elt.sp_send_test_mail_in_first_up;
GO
