#!/bin/bash

# ==============================================================================
# Файл: startup.sh
#
# Назначение:
#   Entrypoint-контейнера MS SQL Server.
#
#   Скрипт выполняет:
#
#   1. Запуск SQL Server в фоне.
#   2. Ожидание готовности SQL Server.
#   3. Выполнение DDL-скриптов:
#        schema/
#        agent/
#        elt/
#        views/
#   4. Запуск главной ETL-процедуры:
#
#        elt.sp_master_etl
#
#   5. После завершения инициализации оставляет SQL Server работать.
#
# Общая схема:
#
#   Docker
#      │
#      ▼
#   startup.sh
#      │
#      ├── запускает sqlservr
#      │
#      ├── ждёт готовности
#      │
#      ├── schema/*.sql
#      │
#      ├── agent/*.sql
#      │
#      ├── elt/*.sql
#      │
#      ├── views/*.sql
#      │
#      ├── EXEC elt.sp_master_etl
#      │
#      └── wait sqlservr
#
# ВАЖНО:
#   Все SQL-файлы внутри каждого каталога выполняются последовательно.
#   Bash ждёт завершения одного sqlcmd перед запуском следующего.
# ==============================================================================


# ==============================================================================
# 0. РЕЖИМЫ BASH
# ==============================================================================

# -e
# Если команда завершилась с ошибкой — Bash завершает выполнение скрипта.
#
# Например:
#
#   run_sql "schema/01_tables.sql"
#   run_sql "schema/02_bad.sql"
#   run_sql "schema/03_tables.sql"
#
# Если 02_bad.sql завершится ошибкой, до 03_tables.sql выполнение
# НЕ дойдёт.
set -e


# -o pipefail
#
# У нас много конструкций вида:
#
#   sqlcmd ... | tee logfile
#
# Без pipefail Bash может увидеть успешное завершение `tee`,
# даже если `sqlcmd` завершился с ошибкой.
#
# pipefail заставляет pipeline считаться ошибочным,
# если ошиблась любая команда внутри него.
set -o pipefail


# -x
#
# Bash будет показывать выполняемые команды в stdout/stderr.
#
# Это удобно при диагностике контейнера.
#
# Например в логе будет видно:
#
#   + run_sql /var/opt/mssql/scripts/schema/01_tables.sql
#
# После отладки можно убрать set -x, если лог станет слишком шумным.
set -x


# ==============================================================================
# 1. НАСТРОЙКИ
# ==============================================================================

# Каталог, куда Docker монтирует наши SQL-скрипты.
SCRIPTS_DIR="/var/opt/mssql/scripts"


# Основной лог startup.sh.
#
# В нём будет:
#
#   - запуск SQL Server;
#   - ожидание готовности;
#   - выполнение SQL-файлов;
#   - запуск ETL;
#   - ошибки;
#   - время выполнения.
LOGFILE="/tmp/startup.log"


# Отдельный лог самого SQL Server.
#
# Это важно разделять:
#
# startup.log  → наш Bash-скрипт
# sqlservr.log → сам SQL Server
#
# Если SQL Server упадёт, мы сможем посмотреть именно его лог.
SQLSERVER_LOG="/tmp/sqlservr.log"


# Максимальное количество попыток ожидания SQL Server.
#
# Ниже одна попытка = 2 секунды.
#
# 45 попыток × 2 секунды = 90 секунд.
MAX_ATTEMPTS=45


# Сколько секунд ждать между попытками.
RETRY_INTERVAL=2


# ==============================================================================
# 2. ФУНКЦИЯ ЛОГИРОВАНИЯ
# ==============================================================================

log()
{
    # Получаем текущее время.
    local timestamp

    timestamp=$(date '+%Y-%m-%d %H:%M:%S')


    # $1 — сообщение, которое передали функции.
    #
    # tee делает две вещи одновременно:
    #
    #   1. показывает сообщение в stdout;
    #   2. записывает его в startup.log.
    #
    # -a означает append — не перезаписывать старый лог.
    echo "[$timestamp] $1" | tee -a "$LOGFILE"
}


# ==============================================================================
# 3. ФУНКЦИЯ ЗАПУСКА SQL-ФАЙЛА
# ==============================================================================

run_sql()
{
    # $1 — путь к SQL-файлу.
    local sql_file="$1"


    log "------------------------------------------------------------"
    log "SQL SCRIPT START: $sql_file"
    log "------------------------------------------------------------"


    # Запоминаем время начала.
    local start_time
    start_time=$(date +%s)


    # --------------------------------------------------------------------------
    # sqlcmd
    #
    # -S localhost
    #     SQL Server находится в этом же контейнере.
    #
    # -U sa
    #     Используем пользователя SA.
    #
    # -P "$MSSQL_SA_PASSWORD"
    #     Пароль берём из переменной окружения Docker.
    #
    # -C
    #     Доверять сертификату SQL Server.
    #
    # -i "$sql_file"
    #     Выполнить указанный SQL-файл.
    #
    # 2>&1
    #     Объединяем stderr и stdout.
    #
    # | tee -a "$LOGFILE"
    #     Одновременно показываем SQL-вывод и записываем его в лог.
    #
    # Благодаря set -o pipefail ошибка sqlcmd не потеряется.
    # --------------------------------------------------------------------------

    if /opt/mssql-tools18/bin/sqlcmd \
        -S localhost \
        -U sa \
        -P "$MSSQL_SA_PASSWORD" \
        -C \
        -i "$sql_file" \
        2>&1 | tee -a "$LOGFILE"
    then

        local end_time
        end_time=$(date +%s)

        local duration
        duration=$((end_time - start_time))

        log "SQL SCRIPT SUCCESS: $sql_file"
        log "Execution time: ${duration} sec"

    else

        local exit_code=$?

        log "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"
        log "SQL SCRIPT FAILED: $sql_file"
        log "Exit code: $exit_code"
        log "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"

        # Важно:
        #
        # Мы НЕ продолжаем выполнение.
        #
        # Если например не создалась таблица,
        # нет смысла запускать процедуры, которые используют эту таблицу.
        return "$exit_code"
    fi
}


# ==============================================================================
# 4. ФУНКЦИЯ ВЫПОЛНЕНИЯ SQL-ЗАПРОСА
# ==============================================================================

run_sql_query()
{
    # $1 — SQL-команда.
    local query="$1"


    log "------------------------------------------------------------"
    log "SQL QUERY START"
    log "Query: $query"
    log "------------------------------------------------------------"


    local start_time
    start_time=$(date +%s)


    # Выполняем SQL-команду через sqlcmd.
    #
    # Например:
    #
    #   EXEC BI_DWH.elt.sp_master_etl;
    #
    # Если процедура завершится ошибкой,
    # благодаря pipefail функция тоже вернёт ошибку.
    if /opt/mssql-tools18/bin/sqlcmd \
        -S localhost \
        -U sa \
        -P "$MSSQL_SA_PASSWORD" \
        -C \
        -Q "$query" \
        2>&1 | tee -a "$LOGFILE"
    then

        local end_time
        end_time=$(date +%s)

        local duration
        duration=$((end_time - start_time))

        log "SQL QUERY SUCCESS"
        log "Execution time: ${duration} sec"

    else

        local exit_code=$?

        log "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"
        log "SQL QUERY FAILED"
        log "Exit code: $exit_code"
        log "Query: $query"
        log "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"

        return "$exit_code"
    fi
}


# ==============================================================================
# 5. НАЧАЛО STARTUP
# ==============================================================================

log "============================================================"
log "STARTUP SCRIPT STARTED"
log "============================================================"

log "Scripts directory: $SCRIPTS_DIR"
log "Startup log:       $LOGFILE"
log "SQL Server log:    $SQLSERVER_LOG"


# ==============================================================================
# 6. ПРОВЕРЯЕМ НАЛИЧИЕ ПАРОЛЯ
# ==============================================================================

# SQL Server использует переменную MSSQL_SA_PASSWORD.
#
# Если её нет, запускать SQL Server бессмысленно.

if [ -z "${MSSQL_SA_PASSWORD:-}" ]; then

    log "ERROR: MSSQL_SA_PASSWORD is not set."

    exit 1

fi

log "MSSQL_SA_PASSWORD is configured."


# ==============================================================================
# 7. ЗАПУСК SQL SERVER
# ==============================================================================

log "============================================================"
log "STARTING SQL SERVER"
log "============================================================"


# Запускаем sqlservr в фоне.
#
# Почему в фоне?
#
# Потому что нам сначала нужно:
#
#   1. запустить SQL Server;
#   2. дождаться его готовности;
#   3. выполнить DDL;
#   4. выполнить ETL.
#
# Поэтому Bash и SQL Server временно работают одновременно.

 /opt/mssql/bin/sqlservr \
    > "$SQLSERVER_LOG" \
    2>&1 &


# PID процесса SQL Server.
SQL_PID=$!


log "SQL Server started."
log "SQL Server PID: $SQL_PID"
log "SQL Server log: $SQLSERVER_LOG"


# ==============================================================================
# 8. ЖДЁМ ГОТОВНОСТИ SQL SERVER
# ==============================================================================

log "============================================================"
log "WAITING FOR SQL SERVER"
log "============================================================"


READY=0


for i in $(seq 1 "$MAX_ATTEMPTS"); do

    # Проверяем, что процесс SQL Server всё ещё жив.
    #
    # kill -0 ничего не убивает.
    # Он просто проверяет существование процесса.
    if ! kill -0 "$SQL_PID" 2>/dev/null; then

        log "ERROR: SQL Server process died."

        log "========== SQL SERVER LOG =========="
        cat "$SQLSERVER_LOG" | tee -a "$LOGFILE"
        log "========== END SQL SERVER LOG ======"

        exit 1
    fi


    # Пытаемся выполнить простой SQL-запрос.
    #
    # Если:
    #
    #   SELECT 1
    #
    # успешно выполняется — SQL Server готов принимать запросы.
    if /opt/mssql-tools18/bin/sqlcmd \
        -S localhost \
        -U sa \
        -P "$MSSQL_SA_PASSWORD" \
        -C \
        -Q "SELECT 1" \
        > /dev/null \
        2>&1
    then

        log "SQL Server is READY."
        log "Ready after attempt: $i/$MAX_ATTEMPTS"

        READY=1
        break

    fi


    log "SQL Server is not ready yet. Attempt $i/$MAX_ATTEMPTS"

    sleep "$RETRY_INTERVAL"

done


# ==============================================================================
# 9. ПРОВЕРЯЕМ, ЧТО SQL SERVER ДЕЙСТВИТЕЛЬНО ЗАПУСТИЛСЯ
# ==============================================================================

if [ "$READY" -ne 1 ]; then

    log "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"
    log "ERROR: SQL Server startup timeout."
    log "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"


    log "========== SQL SERVER LOG =========="
    cat "$SQLSERVER_LOG" | tee -a "$LOGFILE"
    log "========== END SQL SERVER LOG ======"


    exit 1

fi


# ==============================================================================
# 10. ВЫПОЛНЕНИЕ SQL-ФАЙЛОВ
# ==============================================================================

log "============================================================"
log "STARTING DATABASE INITIALIZATION"
log "============================================================"


# Порядок папок имеет значение.
#
# schema
#   ↓
# agent
#   ↓
# elt
#   ↓
# views
#
# Например:
#
# schema создаёт таблицы
# agent создаёт SQL Agent
# elt создаёт ETL-процедуры

#
# Поэтому мы НЕ запускаем все .sql файлы одной кучей.

for stage in schema agent mail elt
do

    STAGE_DIR="$SCRIPTS_DIR/$stage"


    # Если каталога нет — пропускаем его.
    if [ ! -d "$STAGE_DIR" ]; then

        log "Stage '$stage' does not exist. Skipping."

        continue

    fi


    log "============================================================"
    log "STAGE START: $stage"
    log "============================================================"


    # --------------------------------------------------------------------------
    # Получаем SQL-файлы.
    #
    # sort гарантирует порядок:
    #
    # 01_...
    # 02_...
    # 03_...
    #
    # Поэтому имена файлов должны иметь числовой префикс.
    # --------------------------------------------------------------------------

    SQL_FILES=$(find "$STAGE_DIR" \
        -maxdepth 1 \
        -type f \
        -name "*.sql" \
        | sort)


    # Если SQL-файлов нет — ничего не делаем.
    if [ -z "$SQL_FILES" ]; then

        log "No SQL files found in stage '$stage'."

        continue

    fi


    # Выполняем каждый SQL-файл.
    #
    # ВАЖНО:
    #
    # Bash ждёт завершения run_sql.
    #
    # Поэтому:
    #
    #   01.sql
    #      ↓
    #   завершился
    #      ↓
    #   02.sql
    #      ↓
    #   завершился
    #      ↓
    #   03.sql
    #
    # Параллельного запуска здесь нет.

    while IFS= read -r sql_file
    do

        run_sql "$sql_file"

    done <<< "$SQL_FILES"


    log "STAGE SUCCESS: $stage"

done


# ==============================================================================
# 11. ВСЕ SQL-ОБЪЕКТЫ СОЗДАНЫ
# ==============================================================================

log "============================================================"
log "DATABASE INITIALIZATION COMPLETED"
log "============================================================"


# ==============================================================================
# 12. ЗАПУСК MASTER ETL
# ==============================================================================

log "============================================================"
log "STARTING MASTER ETL"
log "============================================================"


# Небольшая пауза не обязательна.
#
# SQL Server уже проверен через SELECT 1.
#
# Поэтому в отличие от старого варианта:
#
#     sleep 10
#
# нам не нужно надеяться, что через 10 секунд всё будет готово.
#
# Мы уже проверили это явно.


ETL_START=$(date +%s)


run_sql_query "USE BI_DWH; EXEC elt.sp_master_etl;"


ETL_END=$(date +%s)
ETL_DURATION=$((ETL_END - ETL_START))


log "============================================================"
log "MASTER ETL COMPLETED"
log "ETL execution time: ${ETL_DURATION} sec"
log "============================================================"


# ==============================================================================
# 13. ИНИЦИАЛИЗАЦИЯ УСПЕШНО ЗАВЕРШЕНА
# ==============================================================================

log "============================================================"
log "STARTUP INITIALIZATION SUCCESSFUL"
log "============================================================"


# ==============================================================================
# 14. ПЕРЕДАЁМ УПРАВЛЕНИЕ SQL SERVER
# ==============================================================================

log "SQL Server is running."
log "Waiting for SQL Server process..."
log "SQL Server PID: $SQL_PID"


# wait блокирует Bash до завершения SQL Server.
#
# Это важно для Docker.
#
# SQL Server является главным процессом контейнера.
#
# Пока SQL Server жив:
#
#     контейнер жив.
#
# Если SQL Server завершится:
#
#     wait вернёт его exit code,
#     контейнер завершится.
wait "$SQL_PID"


# Сохраняем код завершения SQL Server.
EXIT_CODE=$?


log "============================================================"
log "SQL SERVER STOPPED"
log "Exit code: $EXIT_CODE"
log "============================================================"


exit "$EXIT_CODE"