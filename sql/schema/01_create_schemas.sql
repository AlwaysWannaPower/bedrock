-- ============================================================================
-- Файл: 01_create_schemas.sql
--
-- Назначение:
--     Создание базы данных BI_DWH и логических схем, которые разделяют
--     различные уровни хранения и обработки данных.
--
-- Архитектура проекта:
--
--     IMPORT / CSV
--          │
--          ▼
--     staging
--          │
--          ├──────────────► quarantine
--          │                    │
--          │                    └── ошибочные записи
--          │
--          ▼
--         ODS
--          │
--          ▼
--         DWH
--          │
--          ├── dimensions
--          └── facts
--          │
--          ▼
--      datamart
--          │
--          ▼
--       Superset
--
--
-- Назначение схем:
--
--     staging
--         RAW-слой.
--         Содержит данные, загруженные из исходных файлов практически
--         без преобразований.
--
--     ods
--         Optional / промежуточный слой.
--         Используется для очистки, нормализации и преобразования
--         исходных данных перед загрузкой в DWH.
--
--     dwh
--         Основное хранилище данных.
--         Здесь реализуется аналитическая модель по методологии Кимбалла:
--         факты (facts) и измерения (dimensions).
--
--     quarantine
--         Карантинный слой.
--         Сюда могут помещаться записи из staging, которые не проходят
--         необходимые проверки качества данных.
--
--     elt
--         Служебный слой elt.
--         Содержит реестры файлов, журналы запусков, статусы загрузок
--         и другую техническую информацию о работе elt-процессов.
--
--     datamart
--         Аналитические витрины.
--         Содержит подготовленные для BI и Superset наборы данных,
--         которым не требуется выполнять сложную elt-логику при каждом
--         построении отчёта.
--
--
-- Общий принцип:
--
--     Схемы используются не просто для группировки таблиц.
--     Они визуально и логически разделяют ответственность между
--     различными этапами обработки данных.
--
--     Например:
--
--         staging.turnover_raw
--
--     означает:
--
--         "сырая оборотная ведомость, загруженная из источника".
--
--     А:
--
--         dwh.fact_turnover
--
--     будет означать:
--
--         "факт оборота в аналитической модели DWH".
--
--
-- Идемпотентность:
--
--     Скрипт можно выполнять повторно.
--
--     Если база или схема уже существуют, они не создаются повторно.
--     Это позволяет использовать данный файл как первый шаг развёртывания
--     проекта.
--
-- ============================================================================



-- ============================================================================
-- ШАГ 1. Выбираем системную базу master
-- ============================================================================
--
-- База BI_DWH на этом этапе может ещё не существовать.
--
-- Поэтому сначала подключаемся к master.
--
-- В master находятся системные сведения о базах данных SQL Server,
-- включая sys.databases.
--
-- После проверки существования BI_DWH переключимся непосредственно
-- в созданную базу.
-- ============================================================================

USE master;
GO



-- ============================================================================
-- ШАГ 2. Создание базы данных BI_DWH
-- ============================================================================
--
-- Проверяем системное представление sys.databases.
--
-- Если базы BI_DWH ещё нет:
--
--     CREATE DATABASE BI_DWH
--
-- Если база уже существует:
--
--     ничего не делаем.
--
-- Это делает операцию безопасной для повторного запуска.
-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.databases
    WHERE name = N'BI_DWH'
)
BEGIN

    CREATE DATABASE BI_DWH;

END;
GO



-- ============================================================================
-- ШАГ 3. Переключаемся в рабочую базу BI_DWH
-- ============================================================================
--
-- Все последующие схемы будут создаваться уже внутри BI_DWH.
--
-- Важно понимать:
--
--     database
--         └── schema
--               └── table
--
-- Например:
--
--     BI_DWH.staging.turnover_raw
--
-- Здесь:
--
--     BI_DWH          — база данных
--     staging         — схема
--     turnover_raw    — таблица
-- ============================================================================

USE BI_DWH;
GO



-- ============================================================================
-- ШАГ 4. Создание схемы staging
-- ============================================================================
--
-- staging = RAW / STAGING слой.
--
-- Это первая точка попадания данных в базу после чтения исходных файлов.
--
-- Основной принцип staging:
--
--     "Получили из источника → сохранили максимально близко к источнику."
--
-- Поэтому здесь намеренно не выполняются:
--
--     - очистка данных;
--     - бизнес-валидация;
--     - преобразование типов;
--     - расчёт аналитических показателей;
--     - построение связей между сущностями.
--
-- Например, если в CSV дата пришла строкой:
--
--     45292
--
-- staging может сохранить именно:
--
--     '45292'
--
-- а преобразование в настоящий DATE/DATETIME произойдёт позже.
--
-- Это позволяет не потерять исходное значение и при необходимости
-- повторно обработать данные.
-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'staging'
)
BEGIN

    EXEC(N'CREATE SCHEMA staging');

END;
GO



-- ============================================================================
-- ШАГ 5. Создание схемы ods
-- ============================================================================
--
-- ODS (Operational Data Store) в данном проекте является промежуточным
-- слоем между RAW staging и аналитическим DWH.
--
-- Этот слой сделан намеренно, чтобы процесс обработки данных был
-- разделён на понятные этапы:
--
--     staging
--         ↓
--     очистка
--         ↓
--     преобразование типов
--         ↓
--     проверка
--         ↓
--     ods
--         ↓
--     dwh
--
-- В небольшом проекте ODS иногда можно не использовать вообще.
--
-- Однако здесь он полезен как отдельный учебный и архитектурный слой:
-- можно явно увидеть разницу между:
--
--     "данные как пришли"
--
-- и:
--
--     "данные после технической обработки".
--
-- Например:
--
--     staging.turnover_raw
--         date = '45292'
--
--     ods.turnover_clean
--         date = 2024-01-01
--
-- Именно в ODS могут выполняться технические преобразования,
-- необходимые для дальнейшей загрузки DWH.
-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'ods'
)
BEGIN

    EXEC(N'CREATE SCHEMA ods');

END;
GO



-- ============================================================================
-- ШАГ 6. Создание схемы dwh
-- ============================================================================
--
-- dwh = основное аналитическое хранилище.
--
-- В этой схеме будут находиться таблицы, организованные по методологии
-- Кимбалла.
--
-- Основные типы таблиц:
--
--     DIMENSION
--         Описательные сущности:
--
--             dim_material
--             dim_warehouse
--             dim_date
--             ...
--
--     FACT
--         Измеряемые события / показатели:
--
--             fact_turnover
--             fact_prices
--             ...
--
--
-- В отличие от staging, DWH уже не обязан повторять структуру исходного
-- CSV-файла.
--
-- Здесь структура определяется требованиями аналитики.
--
-- Например:
--
--     CSV
--         material_id
--         warehouse_code
--         income_qty
--
--     может превратиться в:
--
--         fact_turnover
--             material_key
--             warehouse_key
--             date_key
--             income_qty
--
-- где ключи уже ссылаются на соответствующие измерения.
-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'dwh'
)
BEGIN

    EXEC(N'CREATE SCHEMA dwh');

END;
GO



-- ============================================================================
-- ШАГ 7. Создание схемы quarantine
-- ============================================================================
--
-- quarantine = карантин ошибочных данных.
--
-- Здесь могут находиться записи, которые были получены из staging,
-- но не прошли необходимые проверки.
--
-- Например:
--
--     staging.turnover_raw
--              │
--              ▼
--         проверка даты
--              │
--        ┌─────┴─────┐
--        │           │
--      valid       invalid
--        │           │
--        ▼           ▼
--       ODS      quarantine
--
--
-- Примеры возможных проблем:
--
--     - некорректная дата;
--     - невозможное числовое значение;
--     - отсутствующий обязательный идентификатор;
--     - неизвестный склад;
--     - нарушение формата исходных данных.
--
-- Важно:
--
--     quarantine не является заменой логированию.
--
--     elt.file_registry / elt.elt_log
--         отвечают за техническое состояние elt;
--
--     quarantine
--         хранит сами проблемные записи.
-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'quarantine'
)
BEGIN

    EXEC(N'CREATE SCHEMA quarantine');

END;
GO



-- ============================================================================
-- ШАГ 8. Создание схемы elt
-- ============================================================================
--
-- elt = служебный слой elt.
--
-- Здесь НЕ должны храниться бизнес-данные.
--
-- Эта схема предназначена для технических объектов, которые помогают
-- управлять и контролировать elt-процесс.
--
-- Например:
--
--     elt.file_registry
--         Реестр обработанных файлов.
--
--     elt.elt_log
--         Журнал запусков elt.
--
--     elt.file_registry позволяет определить:
--
--         - видел ли elt данный файл;
--         - когда он был загружен;
--         - какой у него SHA-256;
--         - успешно ли он загрузился;
--         - произошла ли ошибка.
--
--     elt.elt_log позволяет определить:
--
--         - когда запускался elt;
--         - сколько он выполнялся;
--         - завершился ли успешно;
--         - какая ошибка произошла.
--
--
-- Таким образом:
--
--     elt
--       ├── контроль файлов
--       ├── логирование
--       └── техническое состояние elt
--
-- Эта информация не является частью аналитической модели DWH.
-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'elt'
)
BEGIN

    EXEC(N'CREATE SCHEMA elt');

END;
GO



-- ============================================================================
-- ШАГ 9. Создание схемы datamart
-- ============================================================================
--
-- datamart = слой аналитических витрин.
--
-- В отличие от DWH, витрины ориентированы не столько на хранение
-- универсальной модели данных, сколько на конкретные задачи аналитики.
--
-- Например:
--
--     datamart.sales_monthly
--     datamart.warehouse_turnover
--     datamart.material_prices
--
-- Superset сможет обращаться к таким таблицам непосредственно,
-- не выполняя каждый раз сложные JOIN и агрегации.
--
--
-- Общая цепочка:
--
--     DWH
--       │
--       │ агрегация / подготовка
--       ▼
--     datamart
--       │
--       ▼
--     Apache Superset
--
--
-- При этом datamart не является обязательным местом хранения всех данных.
-- Основные детализированные данные остаются в DWH.
-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'datamart'
)
BEGIN

    EXEC(N'CREATE SCHEMA datamart');

END;
GO



-- ============================================================================
-- ИТОГОВАЯ СТРУКТУРА БАЗЫ
-- ============================================================================
--
-- После выполнения этого файла база BI_DWH будет иметь следующую
-- логическую структуру:
--
--
--     BI_DWH
--     │
--     ├── staging
--     │     └── RAW данные из источников
--     │
--     ├── ods
--     │     └── очищенные / преобразованные данные
--     │
--     ├── quarantine
--     │     └── ошибочные записи
--     │
--     ├── dwh
--     │     ├── dimensions
--     │     └── facts
--     │
--     ├── elt
--     │     ├── file_registry
--     │     └── elt_log
--     │
--     └── datamart
--           └── аналитические витрины
--
--
-- Важное разделение ответственности:
--
--     staging
--         "Что пришло из источника?"
--
--     quarantine
--         "Что из источника оказалось ошибочным?"
--
--     ods
--         "Что получилось после технической очистки?"
--
--     dwh
--         "Как организовать данные для аналитики?"
--
--     elt
--         "Что происходит с самим процессом загрузки?"
--
--     datamart
--         "Что нужно непосредственно BI/аналитикам?"
--
-- ============================================================================
