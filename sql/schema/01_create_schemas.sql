-- ============================================================================
-- Файл: 01_create_schemas.sql
--
-- Назначение:
--     Создание базы данных BI_DWH и логических схем, которые разделяют
--     различные уровни хранения и обработки данных.
-- ============================================================================

-- ============================================================================
-- ШАГ 1. Выбираем системную базу master
-- ============================================================================
--
-- База BI_DWH на этом этапе может ещё не существовать.
-- После проверки существования BI_DWH переключимся непосредственно
-- в созданную базу.
-- ============================================================================

USE master;
GO

-- ============================================================================
-- ШАГ 2. Создание базы данных BI_DWH
-- ============================================================================
--
-- Проверяем системное представление sys.databases.
--
-- Если базы BI_DWH ещё нет:
--
--     CREATE DATABASE BI_DWH
--
-- Если база уже существует:
--
--     ничего не делаем.
--
-- Это делает операцию безопасной для повторного запуска.
-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.databases
    WHERE name = N'BI_DWH'
)
BEGIN

    CREATE DATABASE BI_DWH;

END;
GO



-- ============================================================================
-- ШАГ 3. Переключаемся в рабочую базу BI_DWH
-- ============================================================================
--
-- Все последующие схемы будут создаваться уже внутри BI_DWH.
--
-- Важно понимать:
--
--     database
--         └── schema
--               └── table
-- ============================================================================

USE BI_DWH;
GO
-- ============================================================================
-- ШАГ 4. Создание схемы staging
-- ============================================================================

-- Это первая точка попадания данных в базу после чтения исходных файлов.
--

-- ============================================================================
IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'staging'
)
BEGIN

    EXEC(N'CREATE SCHEMA staging');

END;
GO

-- ============================================================================
-- ШАГ 5. Создание схемы ods
-- ============================================================================
--
-- ODS (Operational Data Store) в данном проекте является промежуточным
-- слоем между RAW staging и аналитическим DWH.
--
-- Этот слой сделан намеренно, чтобы процесс обработки данных был
-- разделён на понятные этапы:
--
--     staging
--         ↓
--     очистка
--         ↓
--     преобразование типов
--         ↓
--     проверка
--         ↓
--     ods
--         ↓
--     dwh
-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'ods'
)
BEGIN

    EXEC(N'CREATE SCHEMA ods');

END;
GO



-- ============================================================================
-- ШАГ 6. Создание схемы dwh
-- ============================================================================
--
-- dwh = основное аналитическое хранилище.
--
-- В этой схеме будут находиться таблицы, организованные по методологии
-- Кимбалла.
--

-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'dwh'
)
BEGIN

    EXEC(N'CREATE SCHEMA dwh');

END;
GO

-- ============================================================================
-- ШАГ 7. Создание схемы quarantine
-- ============================================================================
--
-- quarantine = карантин ошибочных данных.

-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'quarantine'
)
BEGIN

    EXEC(N'CREATE SCHEMA quarantine');

END;
GO



-- ============================================================================
-- ШАГ 8. Создание схемы elt
-- ============================================================================

-- Эта схема предназначена для технических объектов, которые помогают
-- управлять и контролировать elt-процесс.

-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'elt'
)
BEGIN

    EXEC(N'CREATE SCHEMA elt');

END;
GO
-- ============================================================================
-- ШАГ 9. Создание схемы datamart
-- ============================================================================
-- В отличие от DWH, витрины ориентированы не столько на хранение
-- универсальной модели данных, сколько на конкретные задачи аналитики.

-- ============================================================================

IF NOT EXISTS
(
    SELECT 1
    FROM sys.schemas
    WHERE name = N'datamart'
)
BEGIN

    EXEC(N'CREATE SCHEMA datamart');

END;
GO