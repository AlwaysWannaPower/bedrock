-- ============================================================================
-- Файл: 02_staging_tables.sql
--
-- Назначение:
--     Создание RAW / STAGING-таблиц для исходных файлов.
--
-- Архитектурная роль:
--
--     Этот файл создаёт первый табличный слой после источника данных.
--
--     Источник:
--
--         CSV / IMPORT
--             │
--             ▼
--         staging.*_raw
--             │
--             ▼
--             ODS / DWH
--
--
-- Главный принцип staging:
--
--     Данные должны попасть сюда максимально близко к исходному виду.
--
--     Поэтому на этом этапе намеренно НЕ выполняются:
--
--         - очистка;
--         - преобразование типов;
--         - бизнес-валидация;
--         - исправление значений;
--         - расчёт производных показателей;
--         - построение аналитических связей.
--
--
-- Почему поля имеют тип NVARCHAR:
--
--     Исходный файл может содержать:
--
--         45292
--         45292.000000
--         пустое значение
--         некорректное значение
--
--     Если попытаться сразу загрузить это в DATE или DECIMAL,
--     ошибка преобразования может остановить загрузку.
--
--     В RAW-слое мы сначала сохраняем исходное значение как текст.
--
--     Преобразование:
--
--         NVARCHAR → DATE
--         NVARCHAR → DECIMAL
--         NVARCHAR → INT
--
--     будет выполнено позднее, на этапе обработки данных.
--
--
-- Технические поля:
--
--     load_id
--         Уникальный технический идентификатор строки staging.
--         Создаётся автоматически через IDENTITY.
--
--     file_name
--         Имя исходного файла, из которого пришла строка.
--         Используется для data lineage и диагностики.
--
--
--     date_loaded намеренно НЕ используется.
--
--     Время обработки файла уже хранится в:
--
--         elt.file_registry.loaded_at
--
--     Поэтому дублировать эту информацию в каждой строке staging
--     нет необходимости.
--
--
-- Важное замечание о DROP TABLE:
--
--     Ниже таблицы удаляются перед созданием.
--
--     Это удобно на этапе разработки, когда необходимо быстро
--     пересоздать структуру.
--
--     В production такой подход использовать осторожно:
--
--         DROP TABLE
--             ↓
--         удаление всех данных
--
--     Для production-развёртывания структуру лучше изменять
--     отдельными миграциями.
--
--
-- Создаваемые таблицы:
--
--     staging.turnover_raw
--         Сырая оборотная ведомость.
--
--     staging.prices_raw
--         Сырые данные цен материалов.
--
--     staging.warehouses_raw
--         Сырой реестр складов.
--
-- ============================================================================


USE BI_DWH;
GO



-- ============================================================================
-- ТАБЛИЦА №1
-- staging.turnover_raw
--
-- Назначение:
--     Хранение исходных строк оборотной ведомости.
--
-- Соответствует источнику:
--
--     turnover CSV
--
-- Общий поток:
--
--     turnover_*.csv
--           │
--           ▼
--     staging.turnover_raw
--
-- Здесь пока НЕ происходит понимания того, является ли:
--
--     '45292'
--
-- корректной датой.
--
-- Для staging это просто значение, которое пришло из источника.
-- ============================================================================


-- ============================================================================
-- Удаляем существующую таблицу
-- ============================================================================
--
-- OBJECT_ID(..., 'U') проверяет существование пользовательской таблицы.
--
-- Если таблица существует:
--
--     DROP TABLE
--
-- удаляет её вместе со структурой и всеми данными.
--
-- Этот подход используется здесь для удобства разработки:
-- скрипт можно запустить заново и получить чистую структуру.
-- ============================================================================

IF OBJECT_ID(N'staging.turnover_raw', N'U') IS NOT NULL
BEGIN

    DROP TABLE staging.turnover_raw;

END;
GO



-- ============================================================================
-- Создаём staging.turnover_raw
-- ============================================================================

CREATE TABLE staging.turnover_raw
(
    -- ========================================================================
    -- Технический идентификатор строки
    -- ========================================================================
    --
    -- IDENTITY(1,1):
    --
    --     первая строка получает 1;
    --     следующая — 2;
    --     затем — 3 и т.д.
    --
    -- Этот идентификатор НЕ является идентификатором материала,
    -- склада или другой бизнес-сущности.
    --
    -- Он существует исключительно для самой строки staging.
    --
    -- Например:
    --
    --     load_id = 15732
    --
    -- означает только:
    --
    --     "это технически идентифицированная строка staging".
    --
    -- Он не говорит ничего о содержимом строки.
    -- ========================================================================

    load_id INT IDENTITY(1,1) NOT NULL,


    -- ========================================================================
    -- Имя исходного файла
    -- ========================================================================
    --
    -- Позволяет определить происхождение строки.
    --
    -- Например:
    --
    --     turnover_2026_07.csv
    --
    -- Благодаря этому можно выполнить:
    --
    --     SELECT *
    --     FROM staging.turnover_raw
    --     WHERE file_name = N'turnover_2026_07.csv';
    --
    -- Это называется data lineage:
    --
    --     строка DWH/staging
    --             ↓
    --     конкретный исходный файл.
    -- ========================================================================

    file_name NVARCHAR(255) NULL,


    -- ========================================================================
    -- Дата выгрузки
    -- ========================================================================
    --
    -- Оставляем значение как NVARCHAR.
    --
    -- Даже если в дальнейшем это будет настоящая дата,
    -- RAW-слой не должен заниматься её преобразованием.
    -- ========================================================================

    date NVARCHAR(100) NULL,


    -- Дата начала отчётного периода.
    start_date NVARCHAR(100) NULL,


    -- Дата окончания отчётного периода.
    end_date NVARCHAR(100) NULL,


    -- ========================================================================
    -- Код склада
    -- ========================================================================
    --
    -- Оставляем текстовым полем.
    --
    -- Это важно, поскольку код может содержать буквы и ведущие нули.
    --
    -- Например:
    --
    --     S022
    --     00123
    --
    -- Поэтому превращать его в INT на этом этапе нельзя.
    -- ========================================================================

    warehouse_code NVARCHAR(100) NULL,


    -- Остаток на начало периода.
    balance_start NVARCHAR(100) NULL,


    -- Количество поступившего материала.
    income_qty NVARCHAR(100) NULL,


    -- Количество израсходованного материала.
    --
    -- Согласно исходному описанию, значение обычно может быть отрицательным.
    -- ========================================================================

    expense_qty NVARCHAR(100) NULL,


    -- Остаток материала на конец периода.
    balance_end NVARCHAR(100) NULL,


    -- Базовая единица измерения материала.
    unit NVARCHAR(100) NULL,


    -- Идентификатор материала.
    material_id NVARCHAR(100) NULL,


    -- ========================================================================
    -- PRIMARY KEY
    -- ========================================================================
    --
    -- load_id является первичным ключом таблицы.
    --
    -- CONSTRAINT получает явное имя:
    --
    --     PK_staging_turnover_raw
    --
    -- Именованные ограничения удобны для:
    --
    --     - диагностики;
    --     - миграций;
    --     - изменения структуры;
    --     - просмотра системного каталога;
    --     - явной ссылки на конкретное ограничение.
    -- ========================================================================

    CONSTRAINT PK_staging_turnover_raw
        PRIMARY KEY (load_id)
);
GO



-- ============================================================================
-- ТАБЛИЦА №2
-- staging.prices_raw
--
-- Назначение:
--     Хранение исходных данных о ценах материалов.
--
-- Общий поток:
--
--     prices_*.csv
--          │
--          ▼
--     staging.prices_raw
--
-- Как и в turnover_raw, здесь все значения исходного файла
-- сохраняются как NVARCHAR.
-- ============================================================================


-- ============================================================================
-- Удаляем существующую таблицу
-- ============================================================================

IF OBJECT_ID(N'staging.prices_raw', N'U') IS NOT NULL
BEGIN

    DROP TABLE staging.prices_raw;

END;
GO



-- ============================================================================
-- Создаём staging.prices_raw
-- ============================================================================

CREATE TABLE staging.prices_raw
(
    -- Технический идентификатор строки staging.
    load_id INT IDENTITY(1,1) NOT NULL,


    -- Имя исходного файла.
    --
    -- Используется для определения происхождения конкретной строки.
    file_name NVARCHAR(255) NULL,


    -- Дата выгрузки из исходной системы.
    date NVARCHAR(100) NULL,


    -- Начало отчётного периода.
    start_date NVARCHAR(100) NULL,


    -- Конец отчётного периода.
    end_date NVARCHAR(100) NULL,


    -- Идентификатор материала.
    material_id NVARCHAR(100) NULL,


    -- Цена материала.
    --
    -- Здесь она остаётся NVARCHAR.
    --
    -- Преобразование в DECIMAL будет выполняться позднее,
    -- после проверки содержимого.
    price NVARCHAR(100) NULL,


    -- Именованный первичный ключ таблицы.
    CONSTRAINT PK_staging_prices_raw
        PRIMARY KEY (load_id)
);
GO



-- ============================================================================
-- ТАБЛИЦА №3
-- staging.warehouses_raw
--
-- Назначение:
--     Хранение исходного реестра складов.
--
-- Общий поток:
--
--     warehouses.csv
--          │
--          ▼
--     staging.warehouses_raw
--
-- Здесь сохраняются исходные значения без попытки определить,
-- корректны они или нет.
-- ============================================================================


-- ============================================================================
-- Удаляем существующую таблицу
-- ============================================================================

IF OBJECT_ID(N'staging.warehouses_raw', N'U') IS NOT NULL
BEGIN

    DROP TABLE staging.warehouses_raw;

END;
GO



-- ============================================================================
-- Создаём staging.warehouses_raw
-- ============================================================================

CREATE TABLE staging.warehouses_raw
(
    -- Технический идентификатор строки.
    load_id INT IDENTITY(1,1) NOT NULL,


    -- Имя исходного файла.
    --
    -- Позволяет определить, из какого файла появилась строка.
    file_name NVARCHAR(255) NULL,


    -- Дата выгрузки.
    date NVARCHAR(100) NULL,


    -- Начало отчётного периода.
    start_date NVARCHAR(100) NULL,


    -- Конец отчётного периода.
    end_date NVARCHAR(100) NULL,


    -- Код склада.
    warehouse_code NVARCHAR(100) NULL,


    -- Код цеха.
    shop_code NVARCHAR(100) NULL,


    -- Тип склада.
    warehouse_type NVARCHAR(100) NULL,


    -- Дирекция.
    directorate NVARCHAR(100) NULL,


    -- Идентификатор материально ответственного лица.
    mol_id NVARCHAR(100) NULL,


    -- Должность материально ответственного лица.
    mol_position NVARCHAR(100) NULL,


    -- Именованный первичный ключ таблицы.
    CONSTRAINT PK_staging_warehouses_raw
        PRIMARY KEY (load_id)
);
GO



