-- ============================================================================
--
-- После выполнения этого файла структура staging будет следующей:
--
--
--     BI_DWH
--       │
--       └── staging
--             │
--             ├── turnover_raw
--             │     ├── load_id
--             │     ├── file_name
--             │     ├── date
--             │     ├── start_date
--             │     ├── end_date
--             │     ├── warehouse_code
--             │     ├── balance_start
--             │     ├── income_qty
--             │     ├── expense_qty
--             │     ├── balance_end
--             │     ├── unit
--             │     └── material_id
--             │
--             ├── prices_raw
--             │     ├── load_id
--             │     ├── file_name
--             │     ├── date
--             │     ├── start_date
--             │     ├── end_date
--             │     ├── material_id
--             │     └── price
--             │
--             └── warehouses_raw
--                   ├── load_id
--                   ├── file_name
--                   ├── date
--                   ├── start_date
--                   ├── end_date
--                   ├── warehouse_code
--                   ├── shop_code
--                   ├── warehouse_type
--                   ├── directorate
--                   ├── mol_id
--                   └── mol_position
--
--
-- Ответственность этого слоя:
--
--     staging
--         "Сохранить то, что пришло из источника."
--
-- Ответственность ETL:
--
--     elt
--         "Определить, какой файл нужно загрузить,
--          был ли он уже загружен и успешно ли завершилась загрузка."
--
-- Ответственность ODS:
--
--     ods
--         "Проверить и технически преобразовать данные."
--
-- Ответственность DWH:
--
--     dwh
--         "Представить данные в аналитической модели."
--
-- Поэтому staging намеренно остаётся максимально простым.
--
-- ============================================================================